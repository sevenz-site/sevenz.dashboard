# Turns the raw step captures (raw/<slug>/<n>.png, from temas/*.mjs) into the
# WebP the help centre serves (Web/public/ayuda/<slug>/<n>.webp, 560px wide)
# and updates their sizes in Web/lib/soporte-capturas.ts.
#
#   python towebp.py              # every topic folder present in raw/
#   python towebp.py <slug> ...   # only those topics
#
# TWO GUARDS, both learnt on 2026-11-03 the first time this ran from its new
# home, with only ONE topic re-taken in raw/:
#
#   1. ONLY TOPIC FOLDERS. raw/ also holds scratch captures (a check of the
#      bell, a contact sheet); they were being published as if they were help
#      pages. A folder counts only if its name is a slug in Web/lib/soporte.ts,
#      and only files named <n>.png are steps.
#   2. THE SIZES FILE IS MERGED, NEVER REBUILT FROM raw/. raw/ is git-ignored
#      scratch, so it rarely holds every topic. Rebuilding from it would have
#      dropped the size of every capture not re-taken today, and the pages
#      would have lost their reserved boxes without any error.
import glob, json, os, re, sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..', '..'))
OUT = os.path.join(ROOT, 'Web', 'public', 'ayuda')
SIZES_TS = os.path.join(ROOT, 'Web', 'lib', 'soporte-capturas.ts')
SOPORTE_TS = os.path.join(ROOT, 'Web', 'lib', 'soporte.ts')
os.chdir(HERE)

slugs_validos = set(re.findall(r'slug:\s*"([a-z0-9-]+)"', open(SOPORTE_TS, encoding='utf-8').read()))
pedidos = set(sys.argv[1:])

# What the sizes file already says, so nothing not re-taken today is lost.
meta = {}
for slug, n, w, h in re.findall(r'"([a-z0-9-]+)/(\d+)": \[(\d+), (\d+)\]', open(SIZES_TS, encoding='utf-8').read()):
    meta.setdefault(slug, {})[n] = [int(w), int(h)]

total = 0
grandes = []
hechos = {}
for d in sorted(glob.glob('raw/*')):
    slug = os.path.basename(d)
    if not os.path.isdir(d) or slug not in slugs_validos or (pedidos and slug not in pedidos):
        continue
    pasos = [f for f in glob.glob(os.path.join(d, '*.png')) if re.fullmatch(r'\d+\.png', os.path.basename(f))]
    os.makedirs(os.path.join(OUT, slug), exist_ok=True)
    for f in sorted(pasos, key=lambda f: int(os.path.basename(f)[:-4])):
        n = os.path.basename(f)[:-4]
        im = Image.open(f).convert('RGB')
        w = 560
        h = round(im.height * w / im.width)
        im = im.resize((w, h), Image.LANCZOS)
        p = os.path.join(OUT, slug, f'{n}.webp')
        im.save(p, 'WEBP', quality=82, method=6)
        sz = os.path.getsize(p)
        total += sz
        if sz > 60000:
            grandes.append((p, sz))
        meta.setdefault(slug, {})[n] = [w, h]
        hechos[slug] = hechos.get(slug, 0) + 1

lines = ['// GENERATED by `dashboard/scripts/ayuda/towebp.py` from the captures in',
         '// `public/ayuda/` — width and height of each one, so the page reserves its',
         '// box before it loads. Regenerate it with the pictures, never by hand.',
         'export const CAPTURAS: Record<string, [number, number]> = {']
for slug in sorted(meta):
    for n in sorted(meta[slug], key=int):
        w, h = meta[slug][n]
        lines.append(f'  "{slug}/{n}": [{w}, {h}],')
lines.append('};')
open(SIZES_TS, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')

print('convertidas:', hechos, '· KB', total // 1024, '· de más de 60 KB:', grandes)
print('capturas en soporte-capturas.ts:', sum(len(v) for v in meta.values()))
