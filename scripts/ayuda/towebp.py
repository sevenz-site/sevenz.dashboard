import glob, os, json
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..', '..'))
os.chdir(HERE)
from PIL import Image
OUT=os.path.join(ROOT, 'Web', 'public', 'ayuda')
meta={}; total=0; big=[]
for d in sorted(glob.glob('raw/*')):
    if not os.path.isdir(d): continue
    slug=os.path.basename(d)
    os.makedirs(f'{OUT}/{slug}',exist_ok=True)
    for f in sorted(glob.glob(os.path.join(d,'*.png')), key=lambda f:int(os.path.basename(f)[:-4])):
        n=os.path.basename(f)[:-4]
        im=Image.open(f).convert('RGB')
        w=560; h=round(im.height*w/im.width)
        im=im.resize((w,h),Image.LANCZOS)
        p=f'{OUT}/{slug}/{n}.webp'
        im.save(p,'WEBP',quality=82,method=6)
        sz=os.path.getsize(p); total+=sz
        if sz>60000: big.append((p,sz))
        meta.setdefault(slug,{})[n]=[w,h]
json.dump(meta,open('sizes.json','w'),indent=1)
print('files',sum(len(v) for v in meta.values()),'total KB',total//1024,'max>60k',big)
print({k:len(v) for k,v in meta.items()})

# The sizes map the page reads, so each capture's box is reserved before it loads.
lines=['// GENERATED by `dashboard/scripts/ayuda/towebp.py` from the captures in',
'// `public/ayuda/` — width and height of each one, so the page reserves its',
'// box before it loads. Regenerate it with the pictures, never by hand.',
'export const CAPTURAS: Record<string, [number, number]> = {']
for slug in sorted(meta):
    for n in sorted(meta[slug], key=int):
        w,h=meta[slug][n]; lines.append(f'  "{slug}/{n}": [{w}, {h}],')
lines.append('};')
open(os.path.join(ROOT, 'Web', 'lib', 'soporte-capturas.ts'),'w',encoding='utf-8').write('\n'.join(lines)+'\n')
